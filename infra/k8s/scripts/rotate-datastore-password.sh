#!/usr/bin/env bash

set -euo pipefail

ENV="${ENV:-staging}"
TARGET=""

die() { echo "Error: $1" >&2; exit 1; }
log() { printf '\n\033[1;32m==> %s\033[0m\n' "$1"; }

usage() {
  cat <<EOF
Usage: $(basename "$0") db|db-admin|redis

Rotate an in-cluster datastore password without losing data. These passwords
are generated by deploy-stateful.sh, live only in the cluster (never in git)
and, for Postgres, are baked into the data volume, so changing the Secret
alone would break every connection.

  db        Postgres app role (Secret fmi-codes-db, key password). Alters the
            role, updates the Secret, restarts the backend.
  db-admin  Postgres superuser (key postgres-password). Nothing in the app
            uses it, so nothing is restarted.
  redis     Redis + Sentinel (Secret fmi-codes-redis). Stops all Redis pods,
            updates the Secret, starts them again, then restarts the backend.
            Redis is down for a minute or two; the app keeps working without
            it (ADR-003). Re-running also repairs a Redis left half-rotated.

The new password is generated here and never printed or passed as an
argument. A db/db-admin run that dies halfway keeps the new password in the
Secret as <key>-next; running the same command again finishes the rotation.

Env overrides: ENV (prod|staging, default staging), NAMESPACE,
BACKEND (default deployment/backend), READY_TIMEOUT (seconds, default 300).
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    db|db-admin|redis) [ -z "$TARGET" ] || die "only one target per run"; TARGET="$1"; shift ;;
    *) die "unknown argument '$1' (see --help)" ;;
  esac
done
[ -n "$TARGET" ] || { usage; exit 1; }

case "$ENV" in
  prod)    NAMESPACE="${NAMESPACE:-fmi-codes}"; VALUES_DIR="helm-values" ;;
  staging) NAMESPACE="${NAMESPACE:-fmi-codes-staging}"; VALUES_DIR="overlays/staging" ;;
  *)       die "ENV must be 'prod' or 'staging', got '$ENV'." ;;
esac
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
K8S_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
POSTGRES_VALUES="$K8S_DIR/$VALUES_DIR/postgresql-values.yaml"
REDIS_VALUES="$K8S_DIR/$VALUES_DIR/redis-values.yaml"
DB_SECRET="fmi-codes-db"
REDIS_SECRET="fmi-codes-redis"
POSTGRES_POD="postgres-0"
POSTGRES_CONTAINER="postgresql"
REDIS_STS="redis-node"
BACKEND="${BACKEND:-deployment/backend}"
READY_TIMEOUT="${READY_TIMEOUT:-300}"

command -v kubectl >/dev/null 2>&1 || die "kubectl not found — run install-tools.sh first."
command -v python3 >/dev/null 2>&1 || die "python3 not found — sudo apt-get install -y python3"
kubectl cluster-info >/dev/null 2>&1 || die "no reachable cluster."
kubectl get namespace "$NAMESPACE" >/dev/null 2>&1 || die "namespace '$NAMESPACE' not found."

# Secret values only ever travel through variables, stdin and the environment:
# an argument would be readable by every local user via ps.
secret_get() {
  kubectl -n "$NAMESPACE" get secret "$1" -o "jsonpath={.data.$2}" | base64 -d
}

# stdin: JSON object of key -> plaintext value (null removes the key)
secret_patch() {
  python3 -c '
import base64, json, sys
data = {k: (None if v is None else base64.b64encode(v.encode()).decode())
        for k, v in json.load(sys.stdin).items()}
print(json.dumps({"data": data}))' \
    | kubectl -n "$NAMESPACE" patch secret "$1" --type merge --patch-file /dev/stdin >/dev/null
}

gen_password() {
  python3 -c 'import secrets, string; a = string.ascii_letters + string.digits; print("".join(secrets.choice(a) for _ in range(32)))'
}

restart_backend() {
  if kubectl -n "$NAMESPACE" get "$BACKEND" >/dev/null 2>&1; then
    log "Restarting $BACKEND so it reads the new password"
    kubectl -n "$NAMESPACE" rollout restart "$BACKEND"
    kubectl -n "$NAMESPACE" rollout status "$BACKEND" --timeout="${READY_TIMEOUT}s"
  else
    echo "$BACKEND not found in $NAMESPACE; nothing to restart."
  fi
}

# $1 password, $2 user, $3 database; stdin: SQL. The password is the first line
# the pod reads from stdin, so it never appears in any argv.
psql_as() {
  local pw="$1" user="$2" db="$3"
  # shellcheck disable=SC2016 # $0/$1 expand in the pod's shell
  { printf '%s\n' "$pw"; cat; } | kubectl -n "$NAMESPACE" exec -i "$POSTGRES_POD" -c "$POSTGRES_CONTAINER" -- \
    bash -c 'IFS= read -r PGPASSWORD; export PGPASSWORD; exec psql -v ON_ERROR_STOP=1 -h 127.0.0.1 -U "$0" -d "$1" -tAq' "$user" "$db"
}

can_login() {
  [ "$(echo 'SELECT 1;' | psql_as "$1" "$2" "$3" 2>/dev/null)" = "1" ]
}

# SCRAM-SHA-256 verifier computed here, so the plaintext never reaches the server
# (or its statement log); Postgres stores a pre-hashed password as-is.
scram_verifier() {
  # shellcheck disable=SC2016 # the $ signs are literal SCRAM separators
  NEW_PASSWORD="$1" python3 -c '
import base64, hashlib, hmac, os
pw = os.environ["NEW_PASSWORD"].encode()
salt, iterations = os.urandom(16), 4096
salted = hashlib.pbkdf2_hmac("sha256", pw, salt, iterations)
client_key = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
stored_key = hashlib.sha256(client_key).digest()
server_key = hmac.new(salted, b"Server Key", hashlib.sha256).digest()
b64 = lambda b: base64.b64encode(b).decode()
print(f"SCRAM-SHA-256${iterations}:{b64(salt)}${b64(stored_key)}:{b64(server_key)}")'
}

rotate_postgres() {
  local role="$1" key="$2" next_key="$2-next" db_name new old super verifier
  [ -f "$POSTGRES_VALUES" ] || die "missing $POSTGRES_VALUES"
  db_name="$(grep -E '^[[:space:]]+database:' "$POSTGRES_VALUES" | head -1 | awk '{print $2}')"
  [ -n "$db_name" ] || die "could not read auth.database from $POSTGRES_VALUES"
  kubectl -n "$NAMESPACE" get secret "$DB_SECRET" >/dev/null 2>&1 || die "secret $DB_SECRET not found."
  kubectl -n "$NAMESPACE" wait --for=condition=Ready "pod/$POSTGRES_POD" --timeout=60s >/dev/null \
    || die "$POSTGRES_POD is not Ready; fix Postgres before rotating."

  old="$(secret_get "$DB_SECRET" "$key")"
  new="$(secret_get "$DB_SECRET" "$next_key")"
  if [ -n "$new" ]; then
    log "Found $next_key in $DB_SECRET: resuming an interrupted rotation of '$role'"
  else
    log "Generating a new password for '$role' (kept in $DB_SECRET/$next_key until done)"
    new="$(gen_password)"
    NEXT_KEY="$next_key" NEW_PASSWORD="$new" python3 -c \
      'import json, os; print(json.dumps({os.environ["NEXT_KEY"]: os.environ["NEW_PASSWORD"]}))' \
      | secret_patch "$DB_SECRET"
  fi

  # A resumed superuser rotation may already have changed the superuser itself.
  super="$(secret_get "$DB_SECRET" postgres-password)"
  if ! can_login "$super" postgres postgres; then
    if [ "$role" = "postgres" ] && can_login "$new" postgres postgres; then
      super="$new"
    else
      die "cannot log in as the Postgres superuser with the password in $DB_SECRET/postgres-password."
    fi
  fi

  log "Setting the new password on role '$role'"
  verifier="$(scram_verifier "$new")"
  printf 'ALTER ROLE "%s" PASSWORD '"'"'%s'"'"';\n' "$role" "$verifier" | psql_as "$super" postgres postgres >/dev/null
  if [ "$role" = "postgres" ]; then db_name=postgres; fi
  can_login "$new" "$role" "$db_name" || die "'$role' cannot log in with the new password; $DB_SECRET/$next_key still holds it, re-run to retry."
  if [ -n "$old" ] && [ "$old" != "$new" ] && can_login "$old" "$role" "$db_name"; then
    die "the old password still works for '$role'; the rotation did not take effect."
  fi
  echo "Verified: new password logs in, old one is rejected."

  log "Making the new password live in $DB_SECRET/$key"
  KEY="$key" NEXT_KEY="$next_key" NEW_PASSWORD="$new" python3 -c \
    'import json, os; print(json.dumps({os.environ["KEY"]: os.environ["NEW_PASSWORD"], os.environ["NEXT_KEY"]: None}))' \
    | secret_patch "$DB_SECRET"
}

redis_cli() {
  local pod="$1" pw="$2"; shift 2
  printf '%s\n' "$pw" | kubectl -n "$NAMESPACE" exec -i "$pod" -c redis -- \
    bash -c 'IFS= read -r REDISCLI_AUTH; export REDISCLI_AUTH; exec redis-cli --no-auth-warning "$@"' _ "$@"
}

rotate_redis() {
  local new old replicas pods pod roles masters master_pod sentinel_master ready n
  [ -f "$REDIS_VALUES" ] || die "missing $REDIS_VALUES"
  kubectl -n "$NAMESPACE" get secret "$REDIS_SECRET" >/dev/null 2>&1 || die "secret $REDIS_SECRET not found."
  kubectl -n "$NAMESPACE" get statefulset "$REDIS_STS" >/dev/null 2>&1 || die "statefulset $REDIS_STS not found."
  # From the values file, not the live StatefulSet: a re-run after dying mid-way
  # would otherwise read the 0 replicas this function scales down to.
  replicas="$(awk '/^replica:/{r=1} r && /replicaCount:/{print $2; exit}' "$REDIS_VALUES")"
  [ -n "$replicas" ] || die "could not read replica.replicaCount from $REDIS_VALUES"
  old="$(secret_get "$REDIS_SECRET" redis-password)"
  new="$(gen_password)"

  # Every Redis and Sentinel process must switch passwords at once: a new pod that
  # starts while an old one is still terminating asks the old Sentinel for the
  # master, gets WRONGPASS, records a master literally named "NOAUTH" and the
  # StatefulSet deadlocks in CrashLoopBackOff. So no pod may be left before the
  # Secret changes. Scaling to 0 stops the controller recreating pods; deleting
  # them directly stops them in parallel, because an OrderedReady scale-down goes
  # one pod at a time and halts while any pod is unhealthy.
  log "Stopping all $REDIS_STS pods (Redis is unavailable until they are back; the app keeps working without it)"
  kubectl -n "$NAMESPACE" scale statefulset "$REDIS_STS" --replicas=0 >/dev/null
  pods="$(kubectl -n "$NAMESPACE" get pods -o name | grep "^pod/$REDIS_STS-" || true)"
  # shellcheck disable=SC2086
  [ -z "$pods" ] || kubectl -n "$NAMESPACE" delete $pods --wait=false --ignore-not-found >/dev/null
  for _ in $(seq 1 $((READY_TIMEOUT / 5))); do
    kubectl -n "$NAMESPACE" get pods -o name | grep -q "^pod/$REDIS_STS-" || break
    sleep 5
  done
  ! kubectl -n "$NAMESPACE" get pods -o name | grep -q "^pod/$REDIS_STS-" \
    || die "$REDIS_STS pods still terminating after ${READY_TIMEOUT}s; re-run once they are gone."

  log "Updating $REDIS_SECRET and starting $replicas $REDIS_STS pods"
  NEW_PASSWORD="$new" python3 -c 'import json, os; print(json.dumps({"redis-password": os.environ["NEW_PASSWORD"]}))' \
    | secret_patch "$REDIS_SECRET"
  kubectl -n "$NAMESPACE" scale statefulset "$REDIS_STS" --replicas="$replicas" >/dev/null

  log "Waiting for all $replicas $REDIS_STS pods to be Ready"
  ready=false
  for _ in $(seq 1 $((READY_TIMEOUT / 5))); do
    n="$(kubectl -n "$NAMESPACE" get pods -o jsonpath='{range .items[*]}{.metadata.name} {.status.conditions[?(@.type=="Ready")].status}{"\n"}{end}' \
      | grep -c "^$REDIS_STS-[0-9]* True$" || true)"
    if [ "$n" = "$replicas" ]; then ready=true; break; fi
    sleep 5
  done
  [ "$ready" = "true" ] || die "$REDIS_STS pods not Ready after ${READY_TIMEOUT}s; check: kubectl -n $NAMESPACE get pods"

  pods="$(kubectl -n "$NAMESPACE" get pods -o name | grep "^pod/$REDIS_STS-" | sed 's#^pod/##')"
  masters=0
  master_pod=""
  for pod in $pods; do
    [ "$(redis_cli "$pod" "$new" ping 2>/dev/null)" = "PONG" ] || die "$pod does not accept the new password."
    [ "$(redis_cli "$pod" "$old" ping 2>&1)" != "PONG" ] || die "$pod still accepts the old password."
    roles="$(redis_cli "$pod" "$new" info replication | tr -d '\r')"
    case "$roles" in
      *role:master*) masters=$((masters + 1)); master_pod="$pod" ;;
      *master_link_status:up*) ;;
      *) die "$pod is a replica that is not linked to its master." ;;
    esac
  done
  [ "$masters" = "1" ] || die "expected exactly one Redis master, found $masters."

  # Compare against the real master: a Sentinel holding the wrong password still
  # answers, with "NOAUTH" as the master's host.
  for pod in $pods; do
    ready=false
    for _ in $(seq 1 30); do
      sentinel_master="$(redis_cli "$pod" "$new" -p 26379 sentinel get-master-addr-by-name mymaster 2>/dev/null | head -1 | tr -d '\r')"
      case "$sentinel_master" in "$master_pod".*) ready=true; break ;; esac
      sleep 2
    done
    [ "$ready" = "true" ] || die "Sentinel in $pod reports master '${sentinel_master:-none}', expected $master_pod."
  done
  echo "Verified: every node accepts only the new password, one master ($master_pod), replicas linked, every Sentinel agrees."
}

case "$TARGET" in
  db)
    db_user="$(grep -E '^[[:space:]]+username:' "$POSTGRES_VALUES" 2>/dev/null | head -1 | awk '{print $2}')"
    [ -n "$db_user" ] || die "could not read auth.username from $POSTGRES_VALUES"
    rotate_postgres "$db_user" password
    restart_backend ;;
  db-admin)
    rotate_postgres postgres postgres-password ;;
  redis)
    rotate_redis
    restart_backend ;;
esac

log "Done: '$TARGET' password rotated in $NAMESPACE. Nothing to commit: these passwords live only in the cluster."
